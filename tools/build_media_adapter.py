"""Generate a minimal VOD pacing extension without modifying the Moonlight checkout."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".deps/moonlight/app/src/streaming/native-media.js"
OUTPUT = ROOT / "vendor/moonlight-native-media-vod.js"
EXPECTED = "a95666afa3b88bb868dca23fce761bf8f366cdad3afab929db950656ccea7ce2"

def transformed():
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != EXPECTED:
        raise ValueError("The pinned native-media source changed")
    text = SOURCE.read_text(encoding="utf8")
    changes = (
        ("if(!ready)return false;\n   var frame=pending", "if(!ready)return false;\n   if(publish!==false&&options.canPublish&&!options.canPublish(pending))return false;\n   var frame=pending"),
        ("if(fps===60&&options.smoothVideo!==false)videoPacer=createVideoPacer(now,1000/fps);", "if(options.videoPacer)videoPacer=options.videoPacer;else if(fps===60&&options.smoothVideo!==false)videoPacer=createVideoPacer(now,1000/fps);"),
        ("ready:gpuFence.ready,\n     present:", "ready:gpuFence.ready,\n     canPublish:function(frame){return !options.presentationDue||options.presentationDue(frame.timestamp);},\n     present:"),
    )
    for original, replacement in changes:
        if text.count(original) != 1:
            raise ValueError("VOD extension anchor missing or ambiguous")
        text = text.replace(original, replacement)
    return "/* Derived from XITRIX/Moonlight-CivSwitch 64cdae7f: three VOD pacing hooks only.\n * Generated by tools/build_media_adapter.py; upstream source is preserved unchanged. */\n" + text

if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(transformed(), encoding="utf8", newline="\n")
    print("Generated VOD media adapter; three timing hooks, native ABI unchanged:", OUTPUT)
